/**
 * The header of a generated TypeScript file and the `producerVersion` member of a JSON artefact
 * name the producer's version; a release bumps it without changing anything else, so drift checks
 * compare both texts with the version taken out (section 13.7).
 */
export function withoutProducerVersion(text: string): string {
  return text
    .replace(/^(\/\/ Generated by keelwerk )\S+/, '$1')
    .replace(/("producerVersion": )"[^"]*"/, '$1""');
}
