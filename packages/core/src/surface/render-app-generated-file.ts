import type { TypeFragment } from './type-fragment.ts';

interface ImportLine {
  readonly module: string;
  readonly names: readonly string[];
}

function compareText(left: string, right: string): number {
  if (left === right) return 0;
  return left < right ? -1 : 1;
}

function importedName(specifier: string): string {
  return specifier.split(' as ')[0] ?? specifier;
}

/** Packages first, then relative files, each sorted: the order Biome's organizer keeps. */
function compareModules(left: string, right: string): number {
  const relative = Number(left.startsWith('.')) - Number(right.startsWith('.'));
  return relative === 0 ? compareText(left, right) : relative;
}

const LINE_WIDTH = 100;

/** One import, wrapped the way Biome's formatter wraps a line over the width. */
function importText({ module, names }: ImportLine): string[] {
  const flat = `import type { ${names.join(', ')} } from '${module}';`;
  if (flat.length <= LINE_WIDTH) return [flat];
  return ['import type {', ...names.map((name) => `  ${name},`), `} from '${module}';`];
}

/** What the generated file of an app is written from. */
export interface AppGeneratedSource {
  /** The version of the generator, named in the header. */
  readonly generatorVersion: string;
  /** The file the app is defined in, relative to the generated file: './app.ts'. */
  readonly appFile: string;
  /** The exported type of the app in that file: `Library`. */
  readonly appType: string;
  /** The head API version the types describe. */
  readonly apiVersion: string;
  /** The surface hash at the head version. */
  readonly hash: string;
  /** Type fragments of the selected transports. */
  readonly fragments: readonly TypeFragment[];
}

/**
 * Writes `keelwerk.generated.ts` next to an app (section 13.7): the app's type fold re-exported
 * once, the typed client, the transports' type fragments and the head API version, in the form Biome
 * keeps unchanged. The result is a function of its argument alone.
 */
export function renderAppGeneratedFile(source: AppGeneratedSource): string {
  const merged = new Map<string, Set<string>>([
    ['@keelwerk/client', new Set(['AppClient'])],
    [
      '@keelwerk/core',
      new Set(['ActionRef as ActionRefOf', 'AppActionTree', 'AppEntities', 'Row']),
    ],
    [source.appFile, new Set([source.appType])],
  ]);
  for (const fragment of source.fragments) {
    const names = merged.get(fragment.module) ?? new Set<string>();
    for (const name of fragment.names) names.add(name);
    merged.set(fragment.module, names);
  }
  const imports: ImportLine[] = [...merged]
    .map(([module, names]) => ({
      module,
      names: [...names].sort((left, right) => compareText(importedName(left), importedName(right))),
    }))
    .sort((left, right) => compareModules(left.module, right.module));
  const declarations = [
    `export type App = ${source.appType};`,
    'export type Entities = AppEntities<App>;',
    'export type Actions = AppActionTree<App>;',
    'export type ActionRef = ActionRefOf<App>;',
    'export type Client = AppClient<App>;',
    'export type RowOf<R extends string> = Row<App, R>;',
    ...[...source.fragments]
      .sort((left, right) => compareText(left.declaration, right.declaration))
      .map((fragment) => `${fragment.declaration};`),
    `export const apiVersion = '${source.apiVersion}';`,
  ];
  return `${[
    `// Generated by keelwerk ${source.generatorVersion} from src/${source.appFile.replace(/^\.\//, '')}. Do not edit. Format keelwerk.generated/1, API version ${source.apiVersion}, surface ${source.hash}`,
    ...imports.flatMap(importText),
    '',
    ...declarations,
  ].join('\n')}\n`;
}
