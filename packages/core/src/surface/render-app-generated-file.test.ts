import { describe, expect, test } from 'vitest';
import { renderAppGeneratedFile } from './render-app-generated-file.ts';

const source = {
  generatorVersion: '0.1.0',
  appFile: './app.ts',
  appType: 'Portal',
  apiVersion: '2027-01-12',
  hash: 'sha256-3q2F',
  fragments: [],
};

describe('renderAppGeneratedFile (section 13.7)', () => {
  test('writes the header, the sorted imports and the re-exports', () => {
    expect(
      renderAppGeneratedFile(source),
    ).toBe(`// Generated by keelwerk 0.1.0 from src/app.ts. Do not edit. Format keelwerk.generated/1, API version 2027-01-12, surface sha256-3q2F
import type { AppClient } from '@keelwerk/client';
import type { ActionRef as ActionRefOf, AppActionTree, AppEntities, Row } from '@keelwerk/core';
import type { Portal } from './app.ts';

export type App = Portal;
export type Entities = AppEntities<App>;
export type Actions = AppActionTree<App>;
export type ActionRef = ActionRefOf<App>;
export type Client = AppClient<App>;
export type RowOf<R extends string> = Row<App, R>;
export const apiVersion = '2027-01-12';
`);
  });

  test('adds the type fragments of transports, imports sorted, and wraps a long import', () => {
    const text = renderAppGeneratedFile({
      ...source,
      fragments: [
        {
          module: '@keelwerk/transport-trpc',
          names: ['TrpcRouterOf'],
          declaration: 'export type TrpcRouter = TrpcRouterOf<App>',
        },
        {
          module: '@keelwerk/core',
          names: ['VeryLongTypeNameForWrapping', 'AnotherVeryLongTypeNameForWrapping'],
          declaration: 'export type Wrapped = VeryLongTypeNameForWrapping<App>',
        },
      ],
    });
    const lines = text.split('\n');
    expect(lines.indexOf("import type { AppClient } from '@keelwerk/client';")).toBe(1);
    expect(text).toContain("import type { TrpcRouterOf } from '@keelwerk/transport-trpc';");
    expect(text).toContain(
      "import type {\n  ActionRef as ActionRefOf,\n  AnotherVeryLongTypeNameForWrapping,\n  AppActionTree,\n  AppEntities,\n  Row,\n  VeryLongTypeNameForWrapping,\n} from '@keelwerk/core';",
    );
    expect(text.indexOf('export type TrpcRouter')).toBeGreaterThan(text.indexOf('RowOf'));
    expect(text.indexOf('@keelwerk/transport-trpc')).toBeLessThan(text.indexOf("'./app.ts'"));
    expect(text.endsWith(';\n')).toBe(true);
  });

  test('is a function of its argument alone', () => {
    expect(renderAppGeneratedFile(source)).toBe(renderAppGeneratedFile({ ...source }));
  });
});
