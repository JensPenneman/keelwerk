import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, test } from 'vitest';
import { renderModuleManifest } from './render-module-manifest.ts';
import { scanModuleDirectory } from './scan-module-directory.ts';

const FIXTURES = new URL('../../test/fixtures/modules/', import.meta.url);

function render(id: string, files: readonly string[], migrations = false): string {
  return renderModuleManifest({
    id,
    scanned: scanModuleDirectory(files),
    migrations,
  });
}

function listing(id: string): string[] {
  const source = new URL(`${id}/src/`, FIXTURES);
  return readdirSync(source, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(fileURLToPath(source), join(entry.parentPath, entry.name)));
}

const LIBRARY = [
  'actions/add-book.ts',
  'actions/find-by-isbn.ts',
  'base.ts',
  'entities/book.ts',
  'errors/isbn-taken.ts',
  'module.generated.ts',
  'policies/add-book/signed-in.ts',
  'policies/book/readers.ts',
  'policies/find-by-isbn/signed-in.ts',
];

const LIBRARY_MANIFEST = `// Generated by keelwerk from the directories of src/. Do not edit. Format keelwerk.module/1.
import { defineModule, type ModuleType } from '@keelwerk/core';
import { addBook } from './actions/add-book.ts';
import { findByIsbn } from './actions/find-by-isbn.ts';
import { libraryBase } from './base.ts';
import { signedIn as addBookSignedIn } from './policies/add-book/signed-in.ts';
import { readers } from './policies/book/readers.ts';
import { signedIn as findByIsbnSignedIn } from './policies/find-by-isbn/signed-in.ts';

const libraryDef = defineModule(libraryBase, {
  actions: { addBook, findByIsbn },
  policies: {
    addBook: { signedIn: addBookSignedIn },
    book: { readers },
    findByIsbn: { signedIn: findByIsbnSignedIn },
  },
});

export interface Library extends ModuleType<typeof libraryDef> {}
export const library: Library = libraryDef;
`;

describe('renderModuleManifest', () => {
  test('the header names the source and the format and no version', () => {
    expect(render('library', LIBRARY).split('\n')[0]).toBe(
      '// Generated by keelwerk from the directories of src/. Do not edit. Format keelwerk.module/1.',
    );
  });

  test('writes the golden manifest of the library fixture', () => {
    expect(render('library', LIBRARY)).toBe(LIBRARY_MANIFEST);
  });

  test.each(['accounts', 'auth', 'hooks', 'teams'])(
    'writes the committed manifest of the %s fixture',
    (id) => {
      const committed = readFileSync(new URL(`${id}/src/module.generated.ts`, FIXTURES), 'utf8');
      expect(scanModuleDirectory(listing(id)).unplaced).toEqual([]);
      expect(render(id, listing(id))).toBe(committed);
    },
  );

  test('does not depend on the order of the listing', () => {
    expect(render('auth', listing('auth').toReversed())).toBe(render('auth', listing('auth')));
  });

  test('aliases only the names that clash, in the form the auth fixture shows', () => {
    const text = render('auth', listing('auth'));
    expect(text).toContain(
      "import { self as credentialSelf } from './policies/credential/self.ts';",
    );
    expect(text).toContain(
      "import { self as accountsProfileSelf } from './contributions/to-accounts/policies/profile/self.ts';",
    );
    expect(text).toContain(
      "import { whoami as accountsWhoami } from './contributions/to-accounts/actions/whoami.ts';",
    );
    expect(text).toContain("import { whoami } from './actions/whoami.ts';");
    expect(text).not.toContain('login as');
  });

  test('names effect and executor parts apart when they share a file name', () => {
    const text = render('hooks', listing('hooks'));
    expect(text).toContain('effects: { post: postEffect }');
    expect(text).toContain('executors: { post: postExecutor }');
  });

  test('keys a schedule and a fill by the file name and imports the name with its kind', () => {
    const text = render('mail-store', [
      'base.ts',
      'schedules/poll-releases.ts',
      'contributions/to-accounts/contribution.ts',
      'contributions/to-accounts/fills/identity-providers.ts',
    ]);
    expect(text).toContain("import { pollReleasesSchedule } from './schedules/poll-releases.ts';");
    expect(text).toContain('schedules: { pollReleases: pollReleasesSchedule }');
    expect(text).toContain(
      'toAccounts: { extensionPoints: { identityProviders: identityProvidersFill } }',
    );
    expect(text).toContain('export const mailStore: MailStore = mailStoreDef;');
    expect(text).toContain("import { mailStoreBase } from './base.ts';");
  });

  test('mounts every kind under its section in the order of section 23.5', () => {
    const text = render('demo', [
      'base.ts',
      'actions/a.ts',
      'actions/thing/b.ts',
      'effects/send.ts',
      'executors/lib/client.ts',
      'executors/send.ts',
      'lifecycle/on-created.ts',
      'policies/read-only-key.ts',
      'reactions/r.ts',
      'services/s.ts',
      'topics/t.ts',
      'versions/v.ts',
    ]);
    const order = [
      'actions:',
      'entityActions:',
      'policies:',
      'reactions:',
      'services:',
      'topics:',
      'lifecycle:',
      'changes:',
      'effects:',
      'executors:',
    ];
    const at = order.map((section) => text.indexOf(`  ${section}`));
    expect(at.every((index) => index > 0)).toBe(true);
    expect(at).toEqual(at.toSorted((a, b) => a - b));
    expect(text).toContain('policies: { readOnlyKey }');
    expect(text).not.toContain('client');
  });

  test('records the migrations beside src as the URL of S-08', () => {
    const text = render('library', LIBRARY, true);
    expect(text).toContain("  migrations: new URL('../migrations/', import.meta.url),\n});");
  });

  test('writes an empty literal for a module without parts', () => {
    expect(render('teams', ['base.ts'])).toContain('defineModule(teamsBase, {});');
  });

  test('breaks a section that does not fit in 100 columns and keeps shorter ones on a line', () => {
    const names = Array.from({ length: 9 }, (_, index) => `actions/long-action-name-${index}.ts`);
    const text = render('demo', names);
    expect(text).toContain('  actions: {\n    longActionName0,');
    expect(text.split('\n').every((line) => line.length <= 100)).toBe(true);
  });

  test('moves a name that collides with the generated identifiers', () => {
    const text = render('demo', ['actions/demo-def.ts', 'actions/define-module.ts']);
    expect(text).toContain('demoDef as demoDefAction');
    expect(text).toContain('defineModule as defineModuleAction');
  });

  test('sorts import paths segment by segment, as Biome does', () => {
    const text = render('demo', [
      'actions/credential-reset.ts',
      'actions/credential/revoke.ts',
      'actions/add-book.ts',
      'actions/add.ts',
      'actions/a10.ts',
      'actions/a9.ts',
      'contributions/to-accounts-when-teams/actions/hello.ts',
      'contributions/to-accounts-when-teams/contribution.ts',
      'contributions/to-accounts/actions/whoami.ts',
      'contributions/to-accounts/contribution.ts',
    ]);
    const paths = [...text.matchAll(/from '(\.[^']+)'/g)].map((match) => match[1]);
    expect(paths).toEqual([
      './actions/a9.ts',
      './actions/a10.ts',
      './actions/add.ts',
      './actions/add-book.ts',
      './actions/credential/revoke.ts',
      './actions/credential-reset.ts',
      './base.ts',
      './contributions/to-accounts/actions/whoami.ts',
      './contributions/to-accounts-when-teams/actions/hello.ts',
    ]);
  });
});
