/** The value of the cookie `name` in a `Cookie` header, or undefined when it holds none. */
export function cookieValueOf(header: string | undefined, name: string): string | undefined {
  for (const part of (header ?? '').split(';')) {
    const [key, ...value] = part.trim().split('=');
    if (key === name) return value.join('=');
  }
  return undefined;
}
