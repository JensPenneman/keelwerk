// Writes, for every app root in the workspace, src/keelwerk.generated.ts and
// generated/api-surface/<app>/<api version>.json, or with --check says which ones have drifted
// (architecture 13.7 and 16.2). WP-59 replaces it with `keelwerk generate`.
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { ApiVersionLedger } from '../packages/core/src/api-versions/api-version-ledger.ts';
import { appendLedgerEntry } from '../packages/core/src/api-versions/append-ledger-entry.ts';
import type { ExpectedLedgerEntry } from '../packages/core/src/api-versions/check-ledger.ts';
import { checkLedger } from '../packages/core/src/api-versions/check-ledger.ts';
import { emptyApiVersionLedger } from '../packages/core/src/api-versions/empty-api-version-ledger.ts';
import { parseApiVersionLedger } from '../packages/core/src/api-versions/parse-api-version-ledger.ts';
import { renderApiVersionLedger } from '../packages/core/src/api-versions/render-api-version-ledger.ts';
import { coreApiVersions } from '../packages/core/src/core-module/core-api-versions.ts';
import { writeModuleManifest } from '../packages/core/src/manifest/write-module-manifest.ts';
import { pascal } from '../packages/core/src/naming/pascal.ts';
import { deriveSurface } from '../packages/core/src/surface/derive-surface.ts';
import { renderAppGeneratedFile } from '../packages/core/src/surface/render-app-generated-file.ts';
import { renderSurfaceArtefact } from '../packages/core/src/surface/render-surface-artefact.ts';
import type { SurfaceSource } from '../packages/core/src/surface/surface-source.ts';
import { version } from '../packages/core/src/version.ts';

const SOURCE_CONDITION = '--conditions=@keelwerk/source';
const here = fileURLToPath(import.meta.url);
const root = join(dirname(here), '..');

// The apps import `@keelwerk/core` by name: Node resolves it to the sources under this condition.
if (!process.execArgv.includes(SOURCE_CONDITION)) {
  const child = spawnSync(
    process.execPath,
    [SOURCE_CONDITION, ...process.execArgv, here, ...process.argv.slice(2)],
    { stdio: 'inherit' },
  );
  process.exit(child.status ?? 1);
}

const SEARCHED = ['packages', 'examples'];
const SKIPPED = new Set(['node_modules', 'dist', 'generated']);
// The app roots: **/fixtures/apps/* and examples/*/apps/*, each with a src/app.ts.
const APP_ROOTS: readonly RegExp[] = [
  /(^|\/)fixtures\/apps\/[^/]+$/,
  /^examples\/[^/]+\/apps\/[^/]+$/,
];

async function walk(directory: string, found: string[]): Promise<void> {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory() || SKIPPED.has(entry.name) || entry.name.startsWith('.')) continue;
    const path = join(directory, entry.name);
    const shown = relative(root, path).split(sep).join('/');
    if (
      APP_ROOTS.some((pattern) => pattern.test(shown)) &&
      existsSync(join(path, 'src', 'app.ts'))
    ) {
      found.push(path);
    } else {
      await walk(path, found);
    }
  }
}

async function appOf(file: string): Promise<SurfaceSource | undefined> {
  const loaded: Record<string, unknown> = await import(pathToFileURL(file).href);
  for (const name of Object.keys(loaded).toSorted()) {
    const value = loaded[name];
    if (typeof value === 'object' && value !== null && Reflect.get(value, 'kind') === 'app') {
      return value as SurfaceSource;
    }
  }
  return undefined;
}

/** The header names the generator's version; a release bumps it without changing what the app implies. */
function withoutGeneratorVersion(text: string): string {
  return text.replace(/^(\/\/ Generated by keelwerk )\S+/, '$1');
}

async function current(path: string): Promise<string | undefined> {
  return readFile(path, 'utf8').catch((error: unknown) => {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return undefined;
    throw error;
  });
}

async function listing(directory: string): Promise<string[]> {
  if (!existsSync(directory)) return [];
  const entries = await readdir(directory, { withFileTypes: true });
  return entries.filter((entry) => entry.isFile()).map((entry) => entry.name);
}

const roots: string[] = [];
for (const searched of SEARCHED) {
  if (existsSync(join(root, searched))) await walk(join(root, searched), roots);
}

const check = process.argv.includes('--check');
const failures: string[] = [];
for (const appRoot of roots.toSorted()) {
  const shown = relative(root, appRoot).split(sep).join('/');
  const appFile = join(appRoot, 'src', 'app.ts');
  const app = await appOf(appFile);
  if (app === undefined) {
    process.stderr.write(`${shown}: src/app.ts exports no app value\n`);
    failures.push(shown);
    continue;
  }
  const appType = pascal(app.id);
  if (!new RegExp(`export (interface|type) ${appType}\\b`).test(await readFile(appFile, 'utf8'))) {
    process.stderr.write(`${shown}: src/app.ts must export the type ${appType} of the app\n`);
    failures.push(shown);
    continue;
  }
  const dates = app.api?.dates ?? coreApiVersions.dates;
  const expected = new Map<string, string>();
  const implied: ExpectedLedgerEntry[] = [];
  let head = '';
  let broken = false;
  for (const date of dates) {
    const derived = deriveSurface(app, date);
    for (const problem of derived.problems) {
      process.stderr.write(`${shown}: ${problem.severity} ${problem.code}: ${problem.message}\n`);
      if (problem.severity === 'error') broken = true;
    }
    expected.set(
      join(appRoot, 'generated', 'api-surface', app.id, `${date}.json`),
      renderSurfaceArtefact(derived.surface),
    );
    head = derived.surface.hash;
    implied.push({
      version: date,
      surfaceHash: derived.surface.hash,
      modules: Object.fromEntries(derived.surface.modules.map((item) => [item.id, item.version])),
    });
  }
  if (broken) {
    failures.push(shown);
    continue;
  }
  expected.set(
    join(appRoot, 'src', 'keelwerk.generated.ts'),
    renderAppGeneratedFile({
      generatorVersion: version,
      appFile: './app.ts',
      appType,
      apiVersion: app.api?.head ?? coreApiVersions.head,
      hash: head,
      fragments: [],
    }),
  );
  const ledgerPath = join(appRoot, 'generated', 'api-surface', app.id, 'ledger.json');
  const ledgerText = await current(ledgerPath);
  const ledger =
    ledgerText === undefined ? emptyApiVersionLedger(app.id) : parseApiVersionLedger(ledgerText);
  if (check) {
    const name = relative(root, ledgerPath).split(sep).join('/');
    if (ledgerText === undefined) {
      process.stderr.write(`${name} does not exist; run node scripts/generate-surfaces.ts\n`);
      failures.push(name);
    }
    for (const problem of ledgerText === undefined ? [] : checkLedger(ledger, app.id, implied)) {
      process.stderr.write(`${name}: ${problem.code}: ${problem.message}\n`);
      failures.push(name);
    }
  } else if (ledgerText === undefined) {
    // Only the first creation: after that the ledger is written by `surface version new` (13.7).
    let next: ApiVersionLedger = ledger;
    for (const entry of implied) next = appendLedgerEntry(next, { ...entry, changes: [] });
    expected.set(ledgerPath, renderApiVersionLedger(next));
  }
  for (const [path, text] of expected) {
    const name = relative(root, path).split(sep).join('/');
    if (check) {
      const committed = await current(path);
      const same =
        committed !== undefined &&
        (path.endsWith('.ts')
          ? withoutGeneratorVersion(committed) === withoutGeneratorVersion(text)
          : committed === text);
      if (!same) {
        process.stderr.write(
          `${name} ${committed === undefined ? 'does not exist' : 'has drifted'}; run node scripts/generate-surfaces.ts\n`,
        );
        failures.push(name);
      }
    } else {
      await mkdir(dirname(path), { recursive: true });
      if (await writeModuleManifest(path, text)) process.stdout.write(`${name} written\n`);
    }
  }
  const artefacts = join(appRoot, 'generated', 'api-surface', app.id);
  for (const file of await listing(artefacts)) {
    if (file !== 'ledger.json' && !expected.has(join(artefacts, file))) {
      const name = relative(root, join(artefacts, file)).split(sep).join('/');
      process.stderr.write(`${name} belongs to no API version of ${app.id}\n`);
      if (check) failures.push(name);
    }
  }
}
process.exitCode = failures.length > 0 ? 1 : 0;
