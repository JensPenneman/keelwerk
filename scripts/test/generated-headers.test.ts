import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const VERSION = /\d+\.\d+\.\d+/;
const HEADER = /^\/\/ Generated by keelwerk from \S/;
const OPENAPI_HEADER = ['apiVersion', 'format', 'producer', 'surface'];

// Reads the tracked files from git, so it checks exactly what is committed.
function tracked(...patterns: string[]): string[] {
  const output = execFileSync('git', ['ls-files', '-z', '--', ...patterns], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  });
  return output.split('\0').filter((path) => path !== '');
}

test('every committed keelwerk header names the source and no version', () => {
  let checked = 0;
  for (const path of tracked('*.generated.ts')) {
    const first = readFileSync(join(repositoryRoot, path), 'utf8').split('\n')[0] ?? '';
    if (!first.startsWith('// Generated by keelwerk')) continue;
    checked += 1;
    expect(first, path).toMatch(HEADER);
    expect(first, path).not.toMatch(VERSION);
  }
  expect(checked).toBeGreaterThanOrEqual(18);
});

test('every committed OpenAPI document names no producer version', () => {
  const files = tracked('*/generated/openapi/*.json');
  expect(files.length).toBeGreaterThan(0);
  for (const path of files) {
    const document = JSON.parse(readFileSync(join(repositoryRoot, path), 'utf8')) as {
      'x-keelwerk-generated'?: Record<string, unknown>;
    };
    const header = document['x-keelwerk-generated'];
    expect(header, path).toBeDefined();
    expect(Object.keys(header ?? {}).sort(), path).toEqual(OPENAPI_HEADER);
    for (const value of Object.values(header ?? {}))
      expect(String(value), path).not.toMatch(VERSION);
  }
});
